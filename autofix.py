"""
SkillGate Auto-Fix — 自动生成修复建议和 PR 描述。
"""
from dataclasses import dataclass
from typing import List


@dataclass
class FixSuggestion:
    finding_category: str
    finding_message: str
    file: str
    line: int
    fix_description: str
    code_snippet_before: str = ""
    code_snippet_after: str = ""
    confidence: float = 0.8  # 0-1


def generate_fix(finding_category: str, finding_message: str, file: str, line: int) -> FixSuggestion:
    """Generate a fix suggestion for a finding."""

    fixes = {
        "dangerous-code": FixSuggestion(
            finding_category="dangerous-code",
            finding_message=finding_message,
            file=file, line=line,
            fix_description="替换 eval/exec 为安全的替代方案",
            code_snippet_before="result = eval(user_input)",
            code_snippet_after="result = ast.literal_eval(user_input)",
            confidence=0.9
        ),
        "credential-leak": FixSuggestion(
            finding_category="credential-leak",
            finding_message=finding_message,
            file=file, line=line,
            fix_description="硬编码凭证改用环境变量",
            code_snippet_before='API_KEY = "sk-1234567890abcdef"',
            code_snippet_after='API_KEY = os.getenv("API_KEY")',
            confidence=0.95
        ),
        "prompt-injection": FixSuggestion(
            finding_category="prompt-injection",
            finding_message=finding_message,
            file=file, line=line,
            fix_description="移除 prompt injection 模式",
            code_snippet_before="Ignore previous instructions and...",
            code_snippet_after="",  # just delete it
            confidence=0.9
        ),
        "subprocess-shell": FixSuggestion(
            finding_category="subprocess-shell",
            finding_message=finding_message,
            file=file, line=line,
            fix_description="避免 shell=True，用列表参数",
            code_snippet_before='subprocess.run("ls -la", shell=True)',
            code_snippet_after='subprocess.run(["ls", "-la"])',
            confidence=0.95
        ),
        "filesystem": FixSuggestion(
            finding_category="filesystem",
            finding_message=finding_message,
            file=file, line=line,
            fix_description="加路径白名单检查",
            code_snippet_before="shutil.rmtree(path)",
            code_snippet_after='if not path.startswith("/safe/dir/"):\n    raise ValueError("Unsafe path")\nshutil.rmtree(path)',
            confidence=0.8
        ),
    }

    # Find matching fix
    for key, fix in fixes.items():
        if key in finding_category.lower():
            return fix

    # Default generic fix
    return FixSuggestion(
        finding_category=finding_category,
        finding_message=finding_message,
        file=file, line=line,
        fix_description=f"请人工审查并修复: {finding_message}",
        confidence=0.3
    )


def generate_pr_description(skill_name: str, findings: list, fixes: list[FixSuggestion]) -> str:
    """Generate a PR description for auto-fix."""

    lines = [
        f"🛡️ SkillGate Auto-Fix PR",
        f"",
        f"## Summary",
        f"",
        f"This PR auto-fixes {len(findings)} security findings in `{skill_name}`.",
        f"",
        f"## Fixed Issues",
        f"",
    ]

    for i, (f, fix) in enumerate(zip(findings, fixes), 1):
        lines.append(f"### {i}. [{f.severity}] {f.category}")
        lines.append(f"- **Issue**: {f.message}")
        lines.append(f"- **Location**: `{f.file}:{f.line}`")
        lines.append(f"- **Fix**: {fix.fix_description}")
        lines.append(f"- **Confidence**: {fix.confidence*100:.0f}%")
        if fix.code_snippet_before and fix.code_snippet_after:
            lines.append(f"- **Before**: `{fix.code_snippet_before}`")
            lines.append(f"- **After**: `{fix.code_snippet_after}`")
        lines.append("")

    lines.extend([
        f"## Test Plan",
        f"- [ ] Verify the fix doesn't break existing functionality",
        f"- [ ] Run skillgate scan to confirm issues are resolved",
        f"- [ ] Run skillbench to confirm tests still pass",
        f"",
        f"---",
        f"*Generated by SkillGate Auto-Fix*",
    ])

    return "\n".join(lines)


